"""Number, date, percentage formatting — Phase 1 placeholder."""


def fmt_congestion(val):
    return f"{val:.1f}"


def fmt_speed(val):
    return f"{val:.1f} km/h"


def fmt_pm25(val):
    return f"{val:.1f} µg/m³"


def fmt_pct(val):
    return f"{val:.1f}%"


def fmt_count(val):
    return f"{int(val):,}"
